import fs from 'fs';
import path from 'path';

import { PortMapping } from './parsePortMappings';

export type ComposeFileOptions = {
  contextDir: string;
  imageName: string;
  serviceName: string;
  volumeName: string;
  portMappings: PortMapping[];
};

/**
 * A docker-compose.yml for running the image on any docker host: the image, the port mappings
 * the frontend was built for, and the one volume holding the app's state. Returns its path.
 */
export const writeComposeFile = ({ contextDir, imageName, serviceName, volumeName, portMappings }: ComposeFileOptions): string => {
  const ports = portMappings.map((mapping) => `      - "${mapping.host}:${mapping.container}"`).join('\n');

  const compose = `# Generated by qpq go. Host ports are baked into the frontend; change them in
# deploy.config.json and rebuild rather than here.
services:
  ${serviceName}:
    image: ${imageName}
    container_name: ${serviceName}
    restart: unless-stopped
    ports:
${ports}
    volumes:
      # All app state (key-value stores, file storage). Swap the named volume for a
      # host path (e.g. /mnt/user/appdata/${serviceName}) to keep it somewhere you can see.
      - ${volumeName}:/app/.qpq-runtime

volumes:
  ${volumeName}:
`;

  const composePath = path.join(contextDir, 'docker-compose.yml');
  fs.writeFileSync(composePath, compose);
  return composePath;
};
