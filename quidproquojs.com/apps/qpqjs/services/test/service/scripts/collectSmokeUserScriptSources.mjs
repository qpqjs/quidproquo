// The test service's build step: gather the sources of apps/qpqjs/userScripts/smoke into
// two generated constants: the files as a map, which the userScript smoke test writes to
// the probe drive and builds with askUserScriptBuild, and the same files zipped, which
// the userScriptZip test writes as one file and builds with askUserScriptBuildFromZip.
// Runs from `npm run build` in this workspace, so `qpq hooks build` (CI local smoke) and
// `npm run build --workspaces` (go:docker) both produce them before anything compiles
// the service. No bundler runs here.
import AdmZip from 'adm-zip';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const serviceDir = dirname(dirname(fileURLToPath(import.meta.url)));
const projectDir = join(serviceDir, '..', '..', '..', 'userScripts', 'smoke');
const generatedDir = join(
  serviceDir,
  'src',
  'smoke',
  'suites',
  'userScript',
  'generated'
);

const listFiles = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? listFiles(join(dir, entry.name))
      : [join(dir, entry.name)]
  );

const srcDir = join(projectDir, 'src');
const sources = Object.fromEntries(
  listFiles(srcDir)
    .sort()
    .map((file) => [
      relative(projectDir, file).split('\\').join('/'),
      readFileSync(file, 'utf8'),
    ])
);

mkdirSync(generatedDir, { recursive: true });

writeFileSync(
  join(generatedDir, 'SMOKE_USER_SCRIPT_SOURCES.ts'),
  [
    '/* eslint-disable */',
    '// Generated by scripts/collectSmokeUserScriptSources.mjs from apps/qpqjs/userScripts/smoke. Do not edit.',
    '/** The smoke user script project, path to text, as the smoke test writes it to the probe drive. */',
    `export const SMOKE_USER_SCRIPT_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)};`,
    '',
  ].join('\n')
);

// Zipped the way a tool zips a folder: wrapped in one top-level directory.
const zip = new AdmZip();
for (const [relativePath, text] of Object.entries(sources)) {
  zip.addFile(`smoke-user-script/${relativePath}`, Buffer.from(text, 'utf8'));
}
writeFileSync(
  join(generatedDir, 'SMOKE_USER_SCRIPT_ZIP_BASE64.ts'),
  [
    '/* eslint-disable */',
    '// Generated by scripts/collectSmokeUserScriptSources.mjs from apps/qpqjs/userScripts/smoke. Do not edit.',
    '/** The smoke user script project as a zip (wrapped in one top-level folder), base64, for askUserScriptBuildFromZip. */',
    `export const SMOKE_USER_SCRIPT_ZIP_BASE64 = ${JSON.stringify(zip.toBuffer().toString('base64'))};`,
    '',
  ].join('\n')
);

console.log(
  `collectSmokeUserScriptSources: wrote generated/SMOKE_USER_SCRIPT_SOURCES.ts (${Object.keys(sources).length} files) and generated/SMOKE_USER_SCRIPT_ZIP_BASE64.ts`
);
