// The test service's build step: bundle apps/qpqjs/userScripts/smoke with the same
// function `qpq script:build` uses, then write the output as a string constant the
// userScript smoke test stores on the probe drive. Runs from `npm run build` in this
// workspace, so `qpq hooks build` (CI local smoke) and `npm run build --workspaces`
// (go:docker) both produce it before anything compiles the service.
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { buildUserScript } = require('quidproquo-deploy-rspack');

const serviceDir = dirname(dirname(fileURLToPath(import.meta.url)));
const projectDir = join(serviceDir, '..', '..', '..', 'userScripts', 'smoke');
const generatedDir = join(
  serviceDir,
  'src',
  'smoke',
  'suites',
  'userScript',
  'generated'
);
const outDir = mkdtempSync(join(tmpdir(), 'smoke-user-script-'));

try {
  const result = await buildUserScript({ projectDir, outDir });
  const built = readFileSync(result.entryPath, 'utf8');

  mkdirSync(generatedDir, { recursive: true });
  writeFileSync(
    join(generatedDir, 'SMOKE_USER_SCRIPT_BUILT.ts'),
    [
      '// Generated by scripts/buildSmokeUserScript.mjs from apps/qpqjs/userScripts/smoke. Do not edit.',
      `/** The built smoke user script; exports ${result.exports.join(', ')}. */`,
      `export const SMOKE_USER_SCRIPT_BUILT = ${JSON.stringify(built)};`,
      '',
    ].join('\n')
  );
  console.log(
    `buildSmokeUserScript: wrote generated/SMOKE_USER_SCRIPT_BUILT.ts (exports ${result.exports.join(', ')})`
  );
} finally {
  rmSync(outDir, { recursive: true, force: true });
}
